#! /bin/bash

PACK=""
if which apt > /dev/null;then
        PACK="apt"
elif which dnf > /dev/null;then
        PACK="dnf"
fi

echo "PACKAGE MANAGER: $PACK"

$PACK update
$PACK install iptables -y

mkdir -p /tmp/bak
cp -r /etc/cron* /tmp/bak
cp -r /etc/pam* /tmp/bak
cp /etc/passwd /tmp/bak

while IFS= read -r line;do
        crontab -l -u $(echo $line | cut -f 1 -d ':')
done < /etc/passwd

systemctl stop crond

$PACK install curl -y

curl -L https://github.com/peass-ng/PEASS-ng/releases/latest/download/linpeas.sh | sh > /linpeas &

echo "SSH CONFIG"

cat << EOF > /tmp/sshd_generic
